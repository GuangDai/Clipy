/// PasteboardAdapter acceptance gates (docs/roadmap/04-pasteboardadapter.md
/// "Acceptance"):
///
/// - Capture freezes all retainable typed representations of the pasteboard
///   item (03a §4; 01 §5.1).
/// - A sibling `org.nspasteboard.ConcealedType` — and every other marker in
///   the configured private/transient set — marks the WHOLE
///   `ClipboardCapture` concealed; sibling plaintext is frozen alongside
///   the marker, never submitted as an ordinary stripped capture.
/// - `write(_:)` clears the pasteboard, writes the payload's Effective
///   Content representations, and writes the lineage hint equal to the item
///   ID; the hint decodes back into `CopyOriginObservation.lineageHint` on
///   the next capture (03b §9; 04 §8; 01 §5.6). End-to-end coalescing via
///   the hint is proven by WS4 through History, not here.
/// - The observer captures the current contents immediately on start, then
///   fires the handler once per distinct `changeCount` bump.
///
/// Every test uses a private `NSPasteboard(name:)` with a unique name, so
/// the suite never reads or mutates the user's clipboard.
import AppKit
import Foundation
import HistoryCore
import Testing
@testable import PasteboardAdapter

// MARK: - Fixtures

/// The six exact marker strings, pinned literally so any drift in
/// `PasteboardMarkers.concealedTypeIdentifiers` fails here (they mirror
/// `IngestPreparationActor.standardTransientTypeIdentifiers`).
private let concealmentMarkers: [String] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "de.petermaurer.TransientPasteboardType",
    "com.agilebits.onepassword",
    "com.typeit4me.clipping",
]

/// A fresh, uniquely named private pasteboard per test.
@MainActor
private func makePasteboard() -> NSPasteboard {
    NSPasteboard(
        name: NSPasteboard.Name("com.clipy.pasteboardadaptertests." + UUID().uuidString)
    )
}

/// Spins the main run loop in short slices until `condition` holds or
/// `timeout` elapses, servicing the observer's main-RunLoop `Timer` (and
/// its main-actor task hops) while the synchronous test body waits.
/// Returns whether the condition was met.
@MainActor
private func spinMainRunLoop(until condition: () -> Bool, timeout: TimeInterval = 2) -> Bool {
    let deadline = Date().addingTimeInterval(timeout)
    while Date() < deadline {
        if condition() { return true }
        _ = RunLoop.main.run(mode: .default, before: Date(timeIntervalSinceNow: 0.02))
    }
    return condition()
}

// MARK: - Capture freeze (03a §4; roadmap 04 acceptance 1)

@Test @MainActor
func captureFreezesEveryRetainableTypedRepresentation() {
    let pasteboard = makePasteboard()
    pasteboard.clearContents()
    pasteboard.setData(Data("plain".utf8), forType: .string)
    pasteboard.setData(Data("<b>rich</b>".utf8), forType: NSPasteboard.PasteboardType("public.html"))

    let observedAt = Date(timeIntervalSince1970: 1_000_000)
    let capture = PasteboardAdapter(pasteboard: pasteboard).capture(observedAt: observedAt)

    #expect(capture != nil)
    #expect(capture?.observedAt == observedAt)
    #expect(capture?.isConcealed == false)
    #expect(capture?.origin.lineageHint == nil)
    #expect(capture?.representations.count == 2)
    #expect(
        capture?.representations.contains {
            $0.typeIdentifier == NSPasteboard.PasteboardType.string.rawValue
                && $0.bytes == Data("plain".utf8)
        } == true
    )
    #expect(
        capture?.representations.contains {
            $0.typeIdentifier == "public.html" && $0.bytes == Data("<b>rich</b>".utf8)
        } == true
    )
}

@Test @MainActor
func captureOfEmptyPasteboardReturnsNil() {
    let pasteboard = makePasteboard()
    pasteboard.clearContents()

    #expect(PasteboardAdapter(pasteboard: pasteboard).capture() == nil)
}

// MARK: - Concealment markers (roadmap 04 acceptance 2)

@Test @MainActor
func everyConcealmentMarkerMarksTheWholeCaptureConcealed() {
    for marker in concealmentMarkers {
        let pasteboard = makePasteboard()
        pasteboard.clearContents()
        pasteboard.setData(Data("sensitive".utf8), forType: .string)
        pasteboard.setData(Data("marker".utf8), forType: NSPasteboard.PasteboardType(marker))

        let capture = PasteboardAdapter(pasteboard: pasteboard).capture()

        #expect(capture?.isConcealed == true, "\(marker)")
        // Whole-capture semantics: the sibling plaintext stays frozen next
        // to its marker so storage rejects the entire observation as
        // `.excludedFromHistory` before fingerprinting — the adapter never
        // strips the marker and submits the plaintext as ordinary content.
        #expect(
            capture?.representations.contains {
                $0.typeIdentifier == NSPasteboard.PasteboardType.string.rawValue
                    && $0.bytes == Data("sensitive".utf8)
            } == true,
            "\(marker)"
        )
    }
}

@Test @MainActor
func marksConcealedRecognizesExactlyTheMarkerSet() {
    for marker in concealmentMarkers {
        #expect(PasteboardMarkers.marksConcealed([marker]), "\(marker)")
        #expect(
            PasteboardMarkers.marksConcealed(["public.utf8-plain-text", marker]),
            "\(marker)"
        )
    }
    #expect(!PasteboardMarkers.marksConcealed(["public.utf8-plain-text", "public.html"]))
    #expect(!PasteboardMarkers.marksConcealed([]))
    #expect(PasteboardMarkers.concealedTypeIdentifiers.count == 6)
    #expect(concealmentMarkers.allSatisfy { PasteboardMarkers.concealedTypeIdentifiers.contains($0) })
}

// MARK: - Lineage hint codec (03b §9; roadmap 04 acceptance 3, codec half)

@Test @MainActor
func lineageHintCodecRoundTripsAndRejectsMalformedData() {
    #expect(PasteboardLineageHint.typeIdentifier == "com.clipy.lineageHint")

    let id = HistoryItemID(rawValue: UUID())
    #expect(PasteboardLineageHint.encode(id) == Data(id.rawValue.uuidString.utf8))
    #expect(PasteboardLineageHint.decode(PasteboardLineageHint.encode(id)) == id)

    #expect(PasteboardLineageHint.decode(Data()) == nil)
    #expect(PasteboardLineageHint.decode(Data("not-a-uuid".utf8)) == nil)
    #expect(
        PasteboardLineageHint.decode(Data("AB108DC6-779D-4C78-B7F5-45BE50EF1CD8".utf8)) != nil
    )
}

// MARK: - Paste write + hint round-trip (03b §9; 04 §8; roadmap 04 acceptance 3)

@Test @MainActor
func writeRoundTripsLineageHintIntoCaptureOrigin() {
    let pasteboard = makePasteboard()
    pasteboard.clearContents()
    let adapter = PasteboardAdapter(pasteboard: pasteboard)

    let id = HistoryItemID(rawValue: UUID())
    let payload = PastePayload(
        item: HistoryItemReference(id: id, contentVersion: ContentVersion(rawValue: 1)),
        representations: [
            HistoryRepresentation(typeIdentifier: "public.utf8-plain-text", bytes: Data("Clipy".utf8)),
            HistoryRepresentation(typeIdentifier: "public.html", bytes: Data("<b>Clipy</b>".utf8)),
        ],
        lineageHint: id
    )

    adapter.write(payload)

    let capture = adapter.capture()
    #expect(capture != nil)
    #expect(capture?.origin.lineageHint == id)
    #expect(capture?.isConcealed == false)
    // The hint marker is metadata: it must not survive as a retained
    // representation of the re-captured paste.
    #expect(capture?.representations.count == 2)
    #expect(
        capture?.representations.contains {
            $0.typeIdentifier == PasteboardLineageHint.typeIdentifier
        } == false
    )
}

@Test @MainActor
func writeClearsPriorContentAndWritesAllRepresentations() {
    let pasteboard = makePasteboard()
    pasteboard.clearContents()
    pasteboard.setData(Data("stale".utf8), forType: NSPasteboard.PasteboardType("com.clipy.tests.stale"))
    let adapter = PasteboardAdapter(pasteboard: pasteboard)

    let id = HistoryItemID(rawValue: UUID())
    adapter.write(
        PastePayload(
            item: HistoryItemReference(id: id, contentVersion: ContentVersion(rawValue: 1)),
            representations: [
                HistoryRepresentation(
                    typeIdentifier: "public.utf8-plain-text",
                    bytes: Data("fresh".utf8)
                )
            ],
            lineageHint: id
        )
    )

    let item = pasteboard.pasteboardItems?.first
    let typeIdentifiers = item?.types.map { $0.rawValue } ?? []
    #expect(typeIdentifiers.contains("public.utf8-plain-text"))
    #expect(typeIdentifiers.contains(PasteboardLineageHint.typeIdentifier))
    #expect(!typeIdentifiers.contains("com.clipy.tests.stale"))
    #expect(item?.data(forType: .string) == Data("fresh".utf8))
    #expect(
        item?.data(forType: NSPasteboard.PasteboardType(PasteboardLineageHint.typeIdentifier))
            == PasteboardLineageHint.encode(id)
    )
}

// MARK: - Observation (01 §5.1; roadmap 04 deliverable 3, acceptance 4)

@Test @MainActor
func observerCapturesImmediatelyThenFiresOncePerChangeCountBump() {
    let pasteboard = makePasteboard()
    pasteboard.clearContents()
    pasteboard.setString("first", forType: .string)
    let observer = PasteboardObserver(
        adapter: PasteboardAdapter(pasteboard: pasteboard),
        pollInterval: 0.05
    )

    var received: [ClipboardCapture] = []
    observer.start { capture in
        received.append(capture)
    }

    // start delivers the CURRENT contents synchronously before returning.
    #expect(received.count == 1)
    #expect(
        received.first?.representations.contains {
            $0.typeIdentifier == NSPasteboard.PasteboardType.string.rawValue
                && $0.bytes == Data("first".utf8)
        } == true
    )

    // A real change (clear + write bumps the change count) is delivered
    // once, with the new contents.
    pasteboard.clearContents()
    pasteboard.setString("second", forType: .string)
    #expect(spinMainRunLoop { received.count >= 2 })
    #expect(
        received.last?.representations.contains {
            $0.typeIdentifier == NSPasteboard.PasteboardType.string.rawValue
                && $0.bytes == Data("second".utf8)
        } == true
    )

    // A change that leaves nothing retainable is recorded but not
    // delivered: the handler fires only for non-nil captures.
    pasteboard.clearContents()
    let deliveredEmptyChange = spinMainRunLoop(until: { received.count >= 3 }, timeout: 0.4)
    #expect(!deliveredEmptyChange)

    observer.stop()
}

@Test @MainActor
func observerStopHaltsDelivery() {
    let pasteboard = makePasteboard()
    pasteboard.clearContents()
    pasteboard.setString("first", forType: .string)
    let observer = PasteboardObserver(
        adapter: PasteboardAdapter(pasteboard: pasteboard),
        pollInterval: 0.05
    )

    var received: [ClipboardCapture] = []
    observer.start { capture in
        received.append(capture)
    }
    observer.stop()

    pasteboard.clearContents()
    pasteboard.setString("after-stop".utf8, forType: .string)
    let deliveredAfterStop = spinMainRunLoop(until: { received.count >= 2 }, timeout: 0.4)
    #expect(!deliveredAfterStop)
    #expect(received.count == 1)
}
