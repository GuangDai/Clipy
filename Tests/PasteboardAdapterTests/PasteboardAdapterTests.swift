        ],
        lineageHint: id
    )

    do {
        try adapter.write(payload)
        Issue.record("SPEC-IMPL-005: expected whole-item write rejection")
    } catch let failure as PasteboardWriteFailure {
        #expect(failure == .itemRejected)
